import { describe, expect, test } from 'bun:test';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { adaptPrompt, codexAgent, copilotAgent, generate, parseAgent } from './agents.ts';

const root = join(import.meta.dir, '..');

const PROMPT =
	'Check that you can call the `mcp__playwright-test__*` tools, starting with `test_run`. Report that\n' +
	'it is missing, and that it connects when a new Claude Code session starts at the\n' +
	'repository root (`/mcp` shows its state).\n\nA path like C:\\tests stays.';

const source = (description: string, tools: string) =>
	`---\nname: playwright-test-healer\ndescription: ${description}\ntools: ${tools}\nmodel: sonnet\n---\n\n` +
	`<!-- Generated by init-agents. -->\n\n${PROMPT}\n`;

const HEALER = parseAgent(
	source(
		"'It''s for failing tests: \"quoted\"'",
		'Read, Grep, Edit, mcp__playwright-test__test_run'
	)
);

describe('parseAgent', () => {
	test('reads name, quoted description, tools and the prompt without the comment', () => {
		expect(HEALER.name).toBe('playwright-test-healer');
		expect(HEALER.description).toBe('It\'s for failing tests: "quoted"');
		expect(HEALER.tools).toEqual(['Read', 'Grep', 'Edit', 'mcp__playwright-test__test_run']);
		expect(HEALER.prompt.startsWith('Check that')).toBe(true);
	});

	test('refuses a tool it cannot carry over', () => {
		expect(() => parseAgent(source('x', 'Read, Bash'))).toThrow(/counterpart.*Bash/);
	});
});

describe('adaptPrompt', () => {
	const target = { tools: 'the T tools', server: 'it is set up in S.' };

	test('names the tools and the server in the other tool’s terms and forbids the secrets', () => {
		const text = adaptPrompt(HEALER.prompt, target);
		expect(text).toContain('call the T tools, starting');
		expect(text).toContain('and that it is set up in S.');
		expect(text).toContain('Never open, print or copy `sap-tests/.env`');
		expect(text).not.toContain('Claude Code');
	});

	test('fails when the Claude Code file no longer has the text it replaces', () => {
		expect(() => adaptPrompt('Something else.', target)).toThrow(/no longer says/);
	});
});

describe('the generated formats', () => {
	test('Copilot: tool sets and MCP tools, the description in YAML quotes', () => {
		const md = copilotAgent(HEALER, 'src.md');
		const head = md.split('\n---\n')[0]!.slice(4);
		expect(Bun.YAML.parse(head)).toMatchObject({
			description: HEALER.description,
			tools: ['search', 'edit', 'playwright-test/test_run']
		});
	});

	test('Codex: the prompt as it is, write access only for an agent that edits', () => {
		const toml = Bun.TOML.parse(codexAgent(HEALER, 'src.md'));
		expect(toml).toMatchObject({
			name: 'playwright_test_healer',
			sandbox_mode: 'workspace-write',
			mcp_servers: { 'playwright-test': { enabled_tools: ['test_run'] } }
		});
		expect(toml).toHaveProperty(
			'developer_instructions',
			expect.stringContaining('A path like C:\\tests stays.')
		);
		const reader = parseAgent(source('x', 'Read, mcp__playwright-test__test_run'));
		expect(Bun.TOML.parse(codexAgent(reader, 'src.md'))).toHaveProperty(
			'sandbox_mode',
			'read-only'
		);
	});

	test('the files in the repository are the ones the script writes', () => {
		for (const [path, content] of generate(root))
			expect({ path, content: readFileSync(join(root, path), 'utf8') }).toEqual({ path, content });
	});
});
