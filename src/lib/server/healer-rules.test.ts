import { mkdirSync, mkdtempSync, rmSync, symlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, test } from 'vitest';
import {
	describeTool,
	parseAgentFile,
	toolDecision,
	unifiedDiff,
	type ToolInput
} from './healer-rules.js';

describe('parseAgentFile', () => {
	test('reads the tools, the model and the prompt without the origin comment', () => {
		const agent = parseAgentFile(
			'---\nname: healer\ndescription: Fixes tests\ntools: Read, Edit, mcp__playwright-test__test_run\nmodel: sonnet\n---\n\n<!-- Generated by init-agents -->\n\nYou are the healer.\n'
		);
		expect(agent).toEqual({
			tools: ['Read', 'Edit', 'mcp__playwright-test__test_run'],
			model: 'sonnet',
			prompt: 'You are the healer.'
		});
	});

	test('the repository healer parses', async () => {
		const { readFileSync } = await import('node:fs');
		const agent = parseAgentFile(
			readFileSync(join(process.cwd(), '.claude/agents/playwright-test-healer.md'), 'utf8')
		);
		expect(agent.tools).toContain('mcp__playwright-test__test_run');
		expect(agent.tools).toContain('Edit');
		expect(agent.prompt).toMatch(/^You are the Playwright Test Healer/);
	});

	test.each([
		['no front matter', 'You are the healer.'],
		['no tools', '---\nname: x\n---\nprompt'],
		['no prompt', '---\ntools: Read\n---\n<!-- only a comment -->\n']
	])('refuses a file with %s', (_what, source) => {
		expect(() => parseAgentFile(source)).toThrow(/^The agent file (has|lists) no/);
	});
});

describe('toolDecision', () => {
	let root = '';
	const allowed = new Set([
		'Read',
		'Glob',
		'Grep',
		'Edit',
		'Write',
		'mcp__playwright-test__test_run',
		'mcp__playwright-test__browser_snapshot',
		'mcp__playwright-test__browser_run_code_unsafe'
	]);
	// The healer's results folder lies in the app's data, outside the repository.
	let output = '';
	const decide = (tool: string, input: ToolInput) =>
		toolDecision(tool, input, root, allowed, output);

	beforeAll(() => {
		root = mkdtempSync(join(tmpdir(), 'healer-rules-'));
		output = mkdtempSync(join(tmpdir(), 'healer-output-'));
		mkdirSync(join(output, 'a-chromium'), { recursive: true });
		mkdirSync(join(root, 'sap-tests/tests/fiori'), { recursive: true });
		mkdirSync(join(root, 'sap-tests/tests/_demo'), { recursive: true });
		mkdirSync(join(root, 'sap-tests/helpers'), { recursive: true });
		writeFileSync(join(root, 'sap-tests/tests/fiori/a.spec.ts'), '');
		writeFileSync(join(root, 'sap-tests/.env'), 'SAP_PASSWORD=x');
		symlinkSync(join(root, 'sap-tests/.env'), join(root, 'sap-tests/tests/fiori/link.ts'));
	});
	afterAll(() => {
		rmSync(root, { recursive: true, force: true });
		rmSync(output, { recursive: true, force: true });
	});

	/** OUT in a path stands for the results folder, which is created only before the tests. */
	const withOutput = (input: ToolInput): ToolInput =>
		Object.fromEntries(
			Object.entries(input).map(([k, v]) => [
				k,
				typeof v === 'string' ? v.replace('OUT', output) : v
			])
		);

	test('allows the tools of the MCP server it lists', () => {
		expect(decide('mcp__playwright-test__test_run', { locations: [] })).toEqual({ allow: true });
	});

	test.each([
		['a tool the agent file does not list', 'Bash', { command: 'cat sap-tests/.env' }],
		['a listed tool it cannot use', 'Write', { file_path: 'README.md', content: '' }],
		[
			'code in the process that holds the passwords, even when the agent file lists it',
			'mcp__playwright-test__browser_run_code_unsafe',
			{ code: 'async () => process.env' }
		],
		[
			'a browser tool that saves to or reads from a file',
			'mcp__playwright-test__browser_snapshot',
			{ filename: '../../sap-tests/.env' }
		]
	])('refuses %s', (_what, tool, input) => {
		expect(decide(tool, input).allow).toBe(false);
	});

	test.each([
		['a test', 'Read', { file_path: 'sap-tests/tests/fiori/a.spec.ts' }],
		['the rules', 'Read', { file_path: 'sap-tests/CLAUDE.md' }],
		['a search in the tests', 'Grep', { pattern: 'getByRoleUI5', path: 'sap-tests/tests' }],
		['a glob in the helpers', 'Glob', { pattern: '**/*.ts', path: 'sap-tests/helpers' }],
		['what its test runs left', 'Read', { file_path: 'OUT/a-chromium/error-context.md' }],
		['a search in what its test runs left', 'Grep', { pattern: 'Error', path: 'OUT' }]
	])('lets it read %s', (_what, tool, input) => {
		expect(decide(tool, withOutput(input))).toEqual({ allow: true });
	});

	test.each([
		['the settings file', 'Read', { file_path: 'sap-tests/.env' }],
		['the settings file by an absolute path', 'Read', { file_path: '/etc/passwd' }],
		['the saved session', 'Read', { file_path: 'sap-tests/.auth/sap-session.json' }],
		['a link to the settings file', 'Read', { file_path: 'sap-tests/tests/fiori/link.ts' }],
		['the app data', 'Read', { file_path: '.data/app.sqlite' }],
		['the results of other runs', 'Read', { file_path: 'test-results/x/trace.zip' }],
		['a saved session beside its results', 'Read', { file_path: 'OUT/.auth/sap.json' }],
		['a search of the whole project', 'Grep', { pattern: 'PASSWORD', path: 'sap-tests' }],
		['a search without a path', 'Grep', { pattern: 'PASSWORD' }],
		['a glob that climbs out', 'Glob', { pattern: '../../*', path: 'sap-tests/tests' }],
		[
			'a search filter that climbs out',
			'Grep',
			{ pattern: 'x', path: 'sap-tests/tests', glob: '../.env' }
		]
	])('refuses to read %s', (_what, tool, input) => {
		expect(decide(tool, withOutput(input)).allow).toBe(false);
	});

	test('lets it change a test and names the file', () => {
		expect(decide('Edit', { file_path: 'sap-tests/tests/fiori/a.spec.ts' })).toEqual({
			allow: true,
			writes: join(root, 'sap-tests/tests/fiori/a.spec.ts')
		});
		expect(decide('Write', { file_path: 'sap-tests/helpers/new.ts', content: '' }).allow).toBe(
			true
		);
	});

	test.each([
		['a test of the demo folder', 'sap-tests/tests/_demo/fails.spec.ts'],
		['the plugin', 'sap-tests/sap-plugin/index.ts'],
		['a file that is not code', 'sap-tests/tests/fiori/notes.md'],
		['the settings file', 'sap-tests/.env'],
		['a link to the settings file', 'sap-tests/tests/fiori/link.ts'],
		['a file outside the repository', '../outside.ts']
	])('refuses to change %s', (_what, file) => {
		expect(decide('Edit', { file_path: file }).allow).toBe(false);
	});
});

describe('describeTool', () => {
	test.each([
		['Read', { file_path: '/repo/sap-tests/tests/a.spec.ts' }, 'Reads sap-tests/tests/a.spec.ts'],
		['Grep', { path: '/repo' }, 'Searches .'],
		['Read', { file_path: '/elsewhere/x.ts' }, 'Reads /elsewhere/x.ts'],
		['mcp__playwright-test__test_run', {}, 'Runs the test']
	])('describes %s %o', (tool, input, line) => {
		expect(describeTool(tool, input, '/repo')).toBe(line);
	});
});

describe('unifiedDiff', () => {
	test('is empty for equal texts', () => {
		expect(unifiedDiff('a\nb', 'a\nb', 'x.ts')).toBe('');
	});

	test('shows a changed line with its context', () => {
		const before = ['1', '2', '3', '4', '5', '6', '7', '8', '9'].join('\n');
		const after = ['1', '2', '3', '4', 'five', '6', '7', '8', '9'].join('\n');
		expect(unifiedDiff(before, after, 'x.ts')).toBe(
			[
				'--- x.ts',
				'+++ x.ts',
				'@@ -2,7 +2,7 @@',
				' 2',
				' 3',
				' 4',
				'-5',
				'+five',
				' 6',
				' 7',
				' 8'
			].join('\n')
		);
	});

	test('splits changes far apart into two hunks', () => {
		const lines = Array.from({ length: 20 }, (_, n) => String(n));
		const after = [...lines];
		after[1] = '1!';
		after[18] = '18!';
		const diff = unifiedDiff(lines.join('\n'), after.join('\n'), 'x.ts');
		expect(diff.match(/^@@/gm)).toHaveLength(2);
	});

	test('shows a new file', () => {
		expect(unifiedDiff(null, 'a', 'x.ts')).toBe(
			['--- /dev/null', '+++ x.ts', '@@ -0,0 +1,1 @@', '+a'].join('\n')
		);
	});
});
